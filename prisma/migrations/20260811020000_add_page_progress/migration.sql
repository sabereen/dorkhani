CREATE TEMPORARY TABLE `khatm_page_progress_backfill` (
    `khatm_id` INTEGER NOT NULL,
    `page_progress` DOUBLE NOT NULL,
    PRIMARY KEY (`khatm_id`)
);

INSERT INTO `khatm_page_progress_backfill` (`khatm_id`, `page_progress`)
SELECT
    ranges.`khatm_id`,
    (100.0 / 604.0) * SUM(
        (LEAST(ranges.`end_ayah`, pages.`end_ayah`) -
         GREATEST(ranges.`start_ayah`, pages.`start_ayah`)) /
        pages.`ayah_count`
    )
FROM (
    SELECT
        `id` AS `khatm_id`,
        0 AS `start_ayah`,
        `verses_read` AS `end_ayah`
    FROM `khatm`
    WHERE `range_type` = 'ayah' AND `verses_read` > 0

    UNION ALL

    SELECT
        parts.`khatm_id`,
        parts.`start` AS `start_ayah`,
        parts.`end` AS `end_ayah`
    FROM `khatm_part` AS parts
    INNER JOIN `khatm` AS khatms ON khatms.`id` = parts.`khatm_id`
    WHERE khatms.`range_type` <> 'ayah' AND parts.`end` > parts.`start`
) AS ranges
INNER JOIN `quran_page_range` AS pages
    ON ranges.`start_ayah` < pages.`end_ayah`
   AND ranges.`end_ayah` > pages.`start_ayah`
GROUP BY ranges.`khatm_id`;

UPDATE `khatm` AS khatms
LEFT JOIN `khatm_page_progress_backfill` AS calculated
    ON calculated.`khatm_id` = khatms.`id`
SET khatms.`page_progress` =
    CASE
        WHEN khatms.`status` = 'completed' OR khatms.`verses_read` >= 6236 THEN 100
        ELSE LEAST(100, GREATEST(0, COALESCE(calculated.`page_progress`, 0)))
    END;

